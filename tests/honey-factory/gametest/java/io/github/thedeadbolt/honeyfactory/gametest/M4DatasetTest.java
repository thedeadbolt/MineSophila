package io.github.thedeadbolt.honeyfactory.gametest;

import com.google.gson.GsonBuilder;
import com.google.gson.JsonObject;
import io.github.thedeadbolt.honeyfactory.contract.DatasetManifest;
import io.github.thedeadbolt.honeyfactory.contract.SampleRecord;
import io.github.thedeadbolt.honeyfactory.contract.SceneRecord;
import io.github.thedeadbolt.honeyfactory.contract.Split;
import io.github.thedeadbolt.honeyfactory.dataset.DatasetValidator;
import io.github.thedeadbolt.honeyfactory.generation.DatasetGenerator;
import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.function.Predicate;
import java.util.stream.Collectors;
import java.util.stream.Stream;
import net.fabricmc.fabric.api.client.gametest.v1.FabricClientGameTest;
import net.fabricmc.fabric.api.client.gametest.v1.context.ClientGameTestContext;
import net.fabricmc.fabric.api.client.gametest.v1.context.TestSingleplayerContext;

/**
 * Roadmap M4 exit gate. Perspective smoke datasets for levels 1–3, each generated by
 * command in a fresh dataset world, reach their exact accepted-scene and target-class
 * quotas, keep every class in the split {@code scene-slots-v1} assigns, satisfy the level's
 * visibility rule and pass validation. A level-2 run cancelled by command after its first
 * accepted scene ends {@code failed}, with its accepted scenes intact and nothing else on
 * disk. Outputs stay under {@code build/m4-datasets} for the outside validator.
 */
public class M4DatasetTest implements FabricClientGameTest {
	private static final int SCENES = 8;
	private static final int VIEWPOINTS = 4;
	private static final int TIMEOUT_TICKS = 20 * 60 * 30;

	@Override
	public void runTest(ClientGameTestContext context) {
		Path output = GameTestSupport.repoRoot().resolve("packages/honey-factory/build/m4-datasets");
		GameTestSupport.deleteRecursively(output);
		GameTestSupport.pinCaptureSettings(context);
		List<String> failures = new ArrayList<>();
		JsonObject summary = new JsonObject();
		for (int level = 1; level <= 3; level++) {
			summary.add("level" + level, smokeDataset(context, level, output.resolve("level" + level), failures));
		}

		summary.add("cancelled", cancelledDataset(context, output.resolve("cancelled"), failures));
		try {
			Files.writeString(output.resolve("summary.json"), new GsonBuilder().setPrettyPrinting().create().toJson(summary) + "\n", StandardCharsets.UTF_8);
		} catch (IOException e) {
			throw new UncheckedIOException(e);
		}

		if (!failures.isEmpty()) {
			throw new AssertionError("M4 dataset failures:\n" + String.join("\n", failures));
		}
	}

	private static JsonObject smokeDataset(ClientGameTestContext context, int level, Path root, List<String> failures) {
		String name = "honey-factory-m4-level" + level;
		DatasetGenerator.Result result = run(context, name, config("m4-smoke-l" + level, level, SCENES, root), progress -> false);
		JsonObject summary = summary(result);
		if (result.failure() != null) {
			failures.add(name + ": generation failed: " + result.failure() + " " + result.validationErrors());
			return summary;
		}

		DatasetValidator.Report report = validate(result.directory(), name, failures);
		DatasetManifest manifest = report.manifest();
		long present = report.scenes().stream().filter(scene -> scene.target().present()).count();
		if (manifest.lifecycle() != DatasetManifest.Lifecycle.COMPLETE || report.scenes().size() != SCENES || report.samples().size() != SCENES * VIEWPOINTS
			|| present != manifest.targetPresentScenes()) {
			failures.add(name + ": quotas not met: " + manifest.counts());
		}

		for (SceneRecord scene : report.scenes()) {
			if (scene.generation().parameters() == null || scene.generation().parameters().viewpointDraws().length != VIEWPOINTS) {
				failures.add(name + ": scene " + scene.sceneId() + " lacks its generation parameters");
			}
		}

		Map<String, Long> statuses = report.samples().stream()
			.collect(Collectors.groupingBy(sample -> sample.target().targetStatus().jsonName(), Collectors.counting()));
		summary.add("target_statuses", new GsonBuilder().create().toJsonTree(statuses));
		summary.add("visibility_ratios", new GsonBuilder().create().toJsonTree(report.samples().stream()
			.map(SampleRecord::target)
			.filter(target -> target.visibilityRatio() != null && target.targetPresent())
			.map(SampleRecord.Target::visibilityRatio)
			.sorted()
			.toList()));
		Map<String, Long> splits = report.scenes().stream()
			.collect(Collectors.groupingBy(scene -> scene.split().jsonName() + (scene.target().present() ? "/present" : "/absent"), Collectors.counting()));
		summary.add("scenes_by_split_and_class", new GsonBuilder().create().toJsonTree(splits));
		return summary;
	}

	/** Cancels a level-2 run by command once it has accepted its first scene. */
	private static JsonObject cancelledDataset(ClientGameTestContext context, Path root, List<String> failures) {
		String name = "honey-factory-m4-cancel";
		DatasetGenerator.Result result = run(context, name, config("m4-cancel", 2, 30, root), progress -> progress.acceptedScenes() >= 1);
		JsonObject summary = summary(result);
		DatasetManifest manifest = result.manifest();
		if (!DatasetGenerator.CANCELLED.equals(result.failure()) || manifest.lifecycle() != DatasetManifest.Lifecycle.FAILED) {
			failures.add(name + ": expected a cancelled, failed dataset, got " + manifest.lifecycle().jsonName() + " (" + result.failure() + ")");
		}

		DatasetValidator.Report report = validate(result.directory(), name, failures);
		DatasetManifest.Counts counts = manifest.counts();
		if (counts.acceptedScenes() < 1 || counts.acceptedScenes() >= 30 || counts.failedScenes() > 1 || report.scenes().size() != counts.acceptedScenes()) {
			failures.add(name + ": unexpected counts after cancelling: " + counts);
		}

		if (manifest.integrity() == null || !manifest.integrity().validationPassed()) {
			failures.add(name + ": the failed manifest does not record a passing validation of what was kept");
		}

		try (Stream<Path> files = Files.walk(result.directory())) {
			long images = files.filter(path -> path.toString().endsWith(".png")).count();
			if (images != 2L * report.samples().size()) {
				failures.add(name + ": " + images + " images on disk for " + report.samples().size() + " samples");
			}
		} catch (IOException e) {
			throw new UncheckedIOException(e);
		}

		return summary;
	}

	private static DatasetGenerator.Result run(ClientGameTestContext context, String name, String config, Predicate<DatasetGenerator.Progress> cancelWhen) {
		try (TestSingleplayerContext world = GameTestSupport.datasetWorld(context, name)) {
			GameTestSupport.claim(world, name);
			return GameTestSupport.generate(context, name, config, cancelWhen, TIMEOUT_TICKS);
		}
	}

	private static DatasetValidator.Report validate(Path directory, String name, List<String> failures) {
		try {
			DatasetValidator.Report report = DatasetValidator.validate(directory);
			if (!report.passed()) {
				failures.add(name + ": validation errors " + report.errors());
			}

			return report;
		} catch (IOException e) {
			throw new UncheckedIOException(e);
		}
	}

	private static JsonObject summary(DatasetGenerator.Result result) {
		DatasetManifest manifest = result.manifest();
		DatasetManifest.Counts counts = manifest.counts();
		JsonObject summary = new JsonObject();
		summary.addProperty("dataset_id", manifest.datasetId());
		summary.addProperty("directory", result.directory().getFileName().toString());
		summary.addProperty("lifecycle", manifest.lifecycle().jsonName());
		summary.addProperty("failure", result.failure());
		summary.addProperty("accepted_scenes", counts.acceptedScenes());
		summary.addProperty("attempted_scenes", counts.attemptedScenes());
		summary.addProperty("failed_scenes", counts.failedScenes());
		summary.addProperty("accepted_samples", counts.acceptedSamples());
		summary.add("rejection_reasons", new GsonBuilder().create().toJsonTree(counts.rejectionReasons()));
		if (manifest.completedAtUtc() != null) {
			summary.addProperty("seconds", java.time.Duration.between(manifest.createdAtUtc(), manifest.completedAtUtc()).toMillis() / 1000.0);
		}

		if (manifest.splitCounts() != null) {
			JsonObject splits = new JsonObject();
			for (Split split : Split.values()) {
				splits.addProperty(split.jsonName(), manifest.splitCounts().get(split).scenes());
			}

			summary.add("split_scenes", splits);
		}

		return summary;
	}

	private static String config(String name, int level, int scenes, Path root) {
		return """
			{
			  "dataset": {"name": "%s", "seed": %d, "difficulty": %d},
			  "viewpoints": {"count": %d},
			  "capture": {"width": 640, "height": 480},
			  "quotas": {"accepted_scenes": %d},
			  "target": {"present_fraction": 0.75},
			  "output": {"root": "%s", "free_space_reserve_bytes": 1073741824}
			}
			""".formatted(name, 2026 + level, level, VIEWPOINTS, scenes, root.toString().replace("\\", "\\\\"));
	}
}
