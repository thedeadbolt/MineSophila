package io.github.thedeadbolt.honeyfactory.gametest;

import com.google.gson.GsonBuilder;
import com.google.gson.JsonObject;
import io.github.thedeadbolt.honeyfactory.HoneyFactory;
import io.github.thedeadbolt.honeyfactory.client.generation.DatasetRuns;
import io.github.thedeadbolt.honeyfactory.client.runtime.EnvironmentRuntime;
import io.github.thedeadbolt.honeyfactory.contract.DatasetManifest;
import io.github.thedeadbolt.honeyfactory.contract.SampleRecord;
import io.github.thedeadbolt.honeyfactory.dataset.DatasetValidator;
import io.github.thedeadbolt.honeyfactory.dataset.PngImages;
import io.github.thedeadbolt.honeyfactory.generation.DatasetGenerator;
import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.Comparator;
import java.util.List;
import java.util.Map;
import java.util.function.Function;
import java.util.stream.Collectors;
import java.util.stream.Stream;
import net.fabricmc.fabric.api.client.gametest.v1.FabricClientGameTest;
import net.fabricmc.fabric.api.client.gametest.v1.context.ClientGameTestContext;
import net.fabricmc.fabric.api.client.gametest.v1.context.TestSingleplayerContext;

/**
 * Roadmap M3 exit gate for generation: a small level-1 dataset generated by command in a
 * fresh dataset world reaches its exact quotas and validates with zero errors; generating
 * it again in a second fresh world reproduces every layout and every mask byte for byte.
 */
public class M3DatasetTest implements FabricClientGameTest {
	private static final int SCENES = 8;
	private static final int VIEWPOINTS = 4;
	private static final int TIMEOUT_TICKS = 20 * 60 * 20;
	private static final int PROGRESS_TICKS = 100;

	@Override
	public void runTest(ClientGameTestContext context) {
		Path output = GameTestSupport.repoRoot().resolve("packages/honey-factory/build/m3-datasets");
		deleteRecursively(output);
		List<String> failures = new ArrayList<>();
		GameTestSupport.pinCaptureSettings(context);
		DatasetValidator.Report first = generate(context, "honey-factory-m3-data-a", output.resolve("a"), failures);
		DatasetValidator.Report second = generate(context, "honey-factory-m3-data-b", output.resolve("b"), failures);
		JsonObject summary = new JsonObject();
		if (first != null && second != null) {
			compare(first, second, failures, summary);
		}

		try {
			Files.writeString(output.resolve("summary.json"), new GsonBuilder().setPrettyPrinting().create().toJson(summary) + "\n", StandardCharsets.UTF_8);
		} catch (IOException e) {
			throw new UncheckedIOException(e);
		}

		if (!failures.isEmpty()) {
			throw new AssertionError("M3 dataset failures:\n" + String.join("\n", failures));
		}
	}

	private static DatasetValidator.Report generate(ClientGameTestContext context, String worldName, Path root, List<String> failures) {
		try (TestSingleplayerContext world = GameTestSupport.datasetWorld(context, worldName)) {
			GameTestSupport.claim(world, worldName);
			String configName = worldName + ".json";
			Path gameDirectory = context.computeOnClient(minecraft -> minecraft.gameDirectory.toPath());
			Files.writeString(gameDirectory.resolve(configName), config(root), StandardCharsets.UTF_8);
			DatasetGenerator.Result previous = context.computeOnClient(minecraft -> DatasetRuns.last());
			context.runOnClient(minecraft -> minecraft.player.connection.sendCommand("honeyfactory_dataset generate " + configName));
			for (int waited = 0; !context.computeOnClient(minecraft -> DatasetRuns.running() == null && DatasetRuns.last() != previous); waited += PROGRESS_TICKS) {
				if (waited >= TIMEOUT_TICKS) {
					throw new AssertionError(worldName + ": generation did not finish within " + TIMEOUT_TICKS + " ticks");
				}

				context.waitTicks(PROGRESS_TICKS);
				context.runOnClient(minecraft -> {
					DatasetGenerator generator = DatasetRuns.running();
					HoneyFactory.LOGGER.info("M3 dataset test: {} {}", generator == null ? null : generator.progress(), EnvironmentRuntime.get().status());
				});
			}

			DatasetGenerator.Result result = context.computeOnClient(minecraft -> DatasetRuns.last());
			if (result.failure() != null) {
				failures.add(worldName + ": generation failed: " + result.failure() + " " + result.validationErrors());
				return null;
			}

			DatasetValidator.Report report = DatasetValidator.validate(result.directory());
			DatasetManifest manifest = report.manifest();
			if (!report.passed()) {
				failures.add(worldName + ": validation errors " + report.errors());
			}

			if (manifest.lifecycle() != DatasetManifest.Lifecycle.COMPLETE || manifest.counts().acceptedScenes() != SCENES
				|| manifest.counts().acceptedSamples() != SCENES * VIEWPOINTS
				|| report.scenes().stream().filter(scene -> scene.target().present()).count() != manifest.targetPresentScenes()) {
				failures.add(worldName + ": quotas not met: " + manifest.counts());
			}

			checkAbsentImages(result.directory(), report, failures);
			return report;
		} catch (IOException e) {
			throw new UncheckedIOException(e);
		}
	}

	/**
	 * A target-absent level-1 image shows only grey floor and blue sky. Honey-coloured pixels
	 * there mean a stale render of an earlier scene, which no mask would reveal.
	 */
	private static void checkAbsentImages(Path root, DatasetValidator.Report report, List<String> failures) throws IOException {
		for (SampleRecord sample : report.samples()) {
			if (sample.target().targetPresent()) {
				continue;
			}

			byte[] rgb = PngImages.decode(Files.readAllBytes(root.resolve(sample.rgb().path()))).data();
			int honey = 0;
			for (int p = 0; p < rgb.length; p += 3) {
				int r = rgb[p] & 0xFF;
				int b = rgb[p + 2] & 0xFF;
				honey += r > 150 && r - b > 100 ? 1 : 0;
			}

			if (honey > 0) {
				failures.add(sample.sampleId() + ": target-absent image has " + honey + " honey-coloured pixels");
			}
		}
	}

	private static void compare(DatasetValidator.Report first, DatasetValidator.Report second, List<String> failures, JsonObject summary) {
		if (!first.manifest().datasetId().equals(second.manifest().datasetId())) {
			failures.add("the same configuration gave dataset IDs " + first.manifest().datasetId() + " and " + second.manifest().datasetId());
		}

		if (!first.scenesDigest().equals(second.scenesDigest())) {
			failures.add("scenes.jsonl differs between the two generations");
		}

		Map<String, SampleRecord> again = second.samples().stream().collect(Collectors.toMap(SampleRecord::sampleId, Function.identity()));
		int masks = 0;
		int rgb = 0;
		for (SampleRecord sample : first.samples()) {
			SampleRecord other = again.get(sample.sampleId());
			if (other == null) {
				failures.add(sample.sampleId() + " is missing from the second generation");
				continue;
			}

			boolean sameMask = sample.mask().sha256().equals(other.mask().sha256());
			boolean sameView = Arrays.equals(sample.camera().playerPosition(), other.camera().playerPosition())
				&& sample.camera().yawDegrees() == other.camera().yawDegrees() && sample.camera().pitchDegrees() == other.camera().pitchDegrees();
			masks += sameMask ? 1 : 0;
			rgb += sample.rgb().sha256().equals(other.rgb().sha256()) ? 1 : 0;
			if (!sameMask || !sameView) {
				failures.add(sample.sampleId() + ": regenerated mask or camera differs");
			}
		}

		summary.addProperty("dataset_id", first.manifest().datasetId());
		summary.addProperty("samples", first.samples().size());
		summary.addProperty("identical_masks", masks);
		summary.addProperty("identical_rgb", rgb);
		summary.addProperty("scenes_sha256", first.scenesDigest().sha256());
		summary.addProperty("attempted_scenes", first.manifest().counts().attemptedScenes());
		summary.add("rejection_reasons", new GsonBuilder().create().toJsonTree(first.manifest().counts().rejectionReasons()));
	}

	private static String config(Path root) {
		return """
			{
			  "dataset": {"name": "m3-smoke", "seed": 2026, "difficulty": 1},
			  "viewpoints": {"count": %d},
			  "capture": {"width": 640, "height": 480},
			  "quotas": {"accepted_scenes": %d},
			  "target": {"present_fraction": 0.75},
			  "output": {"root": "%s"}
			}
			""".formatted(VIEWPOINTS, SCENES, root.toString().replace("\\", "\\\\"));
	}

	private static void deleteRecursively(Path path) {
		if (!Files.exists(path)) {
			return;
		}

		try (Stream<Path> files = Files.walk(path)) {
			for (Path file : files.sorted(Comparator.reverseOrder()).toList()) {
				Files.delete(file);
			}
		} catch (IOException e) {
			throw new UncheckedIOException(e);
		}
	}
}
