/**
 * Roadmap M8 exit gate for in-game replay.
 *
 * <ul>
 *   <li>Three reference datasets are generated by command in fresh dataset worlds: level 1
 *       in perspective, level 4 in panorama and level 5 on natural terrain.</li>
 *   <li>Every scene of each is replayed: the layout checksum matches its record and every
 *       viewpoint's fresh mask equals the stored mask. Levels 1 and 4 replay in another fresh
 *       dataset world; level 5 replays in the world that generated it, since its source
 *       terrain is decorated differently in any other. In a fresh world with the same seed,
 *       the level-5 scenes are reported as a source patch mismatch. One scene is loaded by
 *       command from a sample ID and its viewpoints cycled by command.</li>
 *   <li>Replay is refused in a personal world and in an unclaimed dataset world; a level-5
 *       scene is refused in a world with another seed; a template version this build lacks
 *       is reported as unavailable before the world changes.</li>
 *   <li>No byte under any dataset directory changes.</li>
 * </ul>
 *
 * <p>Results, including RGB differences, are written to {@code build/m8-replay/summary.json}.
 */
public class M8ReplayTest implements FabricClientGameTest {
	private static final long WORLD_SEED = 8_026_031L;
	private static final int GENERATE_TICKS = 20 * 60 * 30;
	private static final int REPLAY_TICKS = 20 * 60 * 10;

	/** {@code replay} holds the replays run in the generation world, when asked for. */
	private record Reference(String name, Path directory, JsonObject replay) {
	}

	@Override
	public void runTest(ClientGameTestContext context) {
		if (GameTestSupport.skipped(this)) {
			return;
		}

		Path output = GameTestSupport.repoRoot().resolve("packages/honey-factory/build/m8-replay");
		GameTestSupport.deleteRecursively(output);
		GameTestSupport.pinCaptureSettings(context);
		List<String> failures = new ArrayList<>();
		List<Reference> references = List.of(
			generate(context, "honey-factory-m8-l1", config("m8-l1", 1, 3, 3, "{\"width\": 320, \"height\": 240}", "", output.resolve("level1")), false, failures),
			generate(context, "honey-factory-m8-l4", config("m8-l4", 4, 2, 2,
				"{\"mode\": \"PANORAMA_310\", \"width\": 620, \"height\": 320, \"cube_face_size\": 256}", "", output.resolve("level4-panorama")), false, failures),
			generate(context, "honey-factory-m8-l5", config("m8-l5", 5, 2, 2, "{\"width\": 320, \"height\": 240}",
				"\"scene\": {\"base\": {\"type\": \"natural_patch\", \"scenes_per_patch\": 2}},", output.resolve("level5")), true, failures)
		);
		Reference natural = references.getLast();
		if (!failures.isEmpty()) {
			throw new AssertionError("M8 reference generation failed:\n" + String.join("\n", failures));
		}

		Map<String, Map<String, String>> before = new TreeMap<>();
		references.forEach(reference -> before.put(reference.name(), hashes(reference.directory())));
		JsonObject summary = new JsonObject();
		JsonObject replays = new JsonObject();
		Path tampered = tamperedCopy(references.getFirst().directory(), output.resolve("tampered"));

		try (TestSingleplayerContext world = GameTestSupport.datasetWorld(context, "honey-factory-m8-replay", WORLD_SEED)) {
			GameTestSupport.claim(world, "honey-factory-m8-replay");
			for (Reference reference : references.subList(0, 2)) {
				replays.add(reference.name(), replayAll(context, reference, failures));
			}

			replays.add(natural.name() + " (generation world)", natural.replay());
			summary.add("replays", replays);
			summary.add("level5_in_another_world", otherWorld(context, natural, failures));
			summary.add("commands", commands(context, references.getFirst(), failures));
			summary.addProperty("unavailable_template", unavailable(context, tampered, failures));
		}

		JsonObject refusals = new JsonObject();
		try (TestSingleplayerContext world = GameTestSupport.datasetWorld(context, "honey-factory-m8-unclaimed", WORLD_SEED + 1)) {
			refusals.addProperty("unclaimed_dataset_world", refusal(context, references.getFirst(), "honey-factory-m8-unclaimed", EnvironmentException.Reason.NOT_OWNED, failures));
			refusals.addProperty("other_world_seed", refusal(context, references.getLast(), "honey-factory-m8-unclaimed", ReplayException.Reason.UNAVAILABLE, failures));
		}

		try (TestSingleplayerContext world = context.worldBuilder().create()) {
			refusals.addProperty("personal_world", refusal(context, references.getFirst(), "personal world", EnvironmentException.Reason.NOT_OWNED, failures));
		}

		summary.add("refusals", refusals);
		for (Reference reference : references) {
			if (!before.get(reference.name()).equals(hashes(reference.directory()))) {
				failures.add(reference.name() + ": replay changed files under the dataset directory");
			}
		}

		summary.addProperty("datasets_unchanged", failures.stream().noneMatch(failure -> failure.contains("changed files")));
		try {
			Files.writeString(output.resolve("summary.json"), new GsonBuilder().setPrettyPrinting().create().toJson(summary) + "\n", StandardCharsets.UTF_8);
		} catch (IOException e) {
			throw new UncheckedIOException(e);
		}

		if (!failures.isEmpty()) {
			throw new AssertionError("M8 replay failures:\n" + String.join("\n", failures));
		}
	}

	/** Generates a reference dataset and, with {@code replayHere}, replays it before leaving its world. */
	private static Reference generate(ClientGameTestContext context, String name, String config, boolean replayHere, List<String> failures) {
		try (TestSingleplayerContext world = GameTestSupport.datasetWorld(context, name, WORLD_SEED)) {
			GameTestSupport.claim(world, name);
			DatasetGenerator.Result result = GameTestSupport.generate(context, name, config, progress -> false, GENERATE_TICKS);
			if (result.failure() != null) {
				failures.add(name + ": generation failed: " + result.failure() + " " + result.validationErrors());
				return new Reference(name, result.directory(), new JsonObject());
			}

			Reference reference = new Reference(name, result.directory(), new JsonObject());
			return replayHere ? new Reference(name, result.directory(), replayAll(context, reference, failures)) : reference;
		}
	}

	/** Level-5 scenes in a fresh world with the generation world's seed: refused as a source patch mismatch. */
	private static JsonObject otherWorld(ClientGameTestContext context, Reference reference, List<String> failures) {
		JsonObject results = new JsonObject();
		for (SceneRecord scene : records(reference.directory())) {
			String result;
			try {
				await(context, () -> ReplayRuns.load(reference.directory(), scene.sceneId()));
				result = "replayed";
			} catch (ReplayException e) {
				result = e.toString();
			}

			if (!result.startsWith(ReplayException.Reason.MISMATCH.name()) || !result.contains("world that generated it")) {
				failures.add(reference.name() + " " + scene.sceneId() + " in another world: expected a source patch mismatch, got " + result);
			}

			results.addProperty(scene.sceneId(), result);
		}

		return results;
	}

	/** Replays every scene of {@code reference} and verifies all its viewpoints. */
	private static JsonObject replayAll(ClientGameTestContext context, Reference reference, List<String> failures) {
		JsonObject scenes = new JsonObject();
		for (SceneRecord scene : records(reference.directory())) {
			String label = reference.name() + " " + scene.sceneId();
			JsonObject entry = new JsonObject();
			try {
				ReplayRuns.Loaded loaded = await(context, () -> ReplayRuns.load(reference.directory(), scene.sceneId()));
				entry.addProperty("layout_matches", loaded.layoutMatches());
				entry.addProperty("render_differences", loaded.renderDifferences().size());
				if (!loaded.layoutMatches()) {
					failures.add(label + ": layout " + loaded.layoutSha256() + " differs from the recorded " + scene.layoutSha256());
				}

				ReplayRuns.Verification verification = await(context, ReplayRuns::verify);
				entry.addProperty("exact", verification.exact());
				JsonArray viewpoints = new JsonArray();
				for (ReplayComparison.Result result : verification.results()) {
					viewpoints.add(new GsonBuilder().create().toJsonTree(result));
					if (!result.maskMatches()) {
						failures.add(label + ": " + result.sampleId() + " mask differs in " + result.maskDifferingPixels() + " pixels");
					}
				}

				entry.add("viewpoints", viewpoints);
				if (verification.results().size() != scene.acceptedSampleCount()) {
					failures.add(label + ": verified " + verification.results().size() + " of " + scene.acceptedSampleCount() + " viewpoints");
				}
			} catch (CompletionException | ReplayException e) {
				failures.add(label + ": replay failed: " + Futures.cause(e));
			}

			scenes.add(scene.sceneId(), entry);
		}

		return scenes;
	}

	/** Loads a sample by command, cycles its viewpoints by command and captures the last. */
	private static JsonObject commands(ClientGameTestContext context, Reference reference, List<String> failures) {
		SceneRecord scene = records(reference.directory()).getFirst();
		String sampleId = scene.sceneId() + "-v01";
		JsonObject summary = new JsonObject();
		command(context, "honeyfactory_replay load " + sampleId + " " + reference.directory());
		context.waitFor(minecraft -> ReplayRuns.current() != null && ReplayRuns.current().sample().sampleId().equals(sampleId), REPLAY_TICKS);
		summary.addProperty("loaded_by_command", ReplayRuns.current() != null && ReplayRuns.current().layoutMatches());
		List<Integer> visited = new ArrayList<>();
		visited.add(context.computeOnClient(minecraft -> ReplayRuns.current().viewpoint()));
		for (String move : new String[] {"next", "next", "previous", "0"}) {
			int expected = Math.floorMod(switch (move) {
				case "next" -> visited.getLast() + 1;
				case "previous" -> visited.getLast() - 1;
				default -> Integer.parseInt(move);
			}, scene.acceptedSampleCount());
			command(context, "honeyfactory_replay viewpoint " + move);
			context.waitFor(minecraft -> ReplayRuns.current().viewpoint() == expected && EnvironmentRuntime.get().status().current() == null, REPLAY_TICKS);
			visited.add(expected);
		}

		JsonArray order = new JsonArray();
		visited.forEach(order::add);
		summary.add("viewpoints_visited", order);
		if (!visited.equals(List.of(1, 2, 0, 2, 0))) {
			failures.add("command viewpoints visited " + visited);
		}

		ReplayRuns.Verification capture = await(context, ReplayRuns::capture);
		summary.addProperty("capture_mask_matches", capture.results().getFirst().maskMatches());
		if (!capture.results().getFirst().maskMatches() || !capture.results().getFirst().sampleId().equals(scene.sceneId() + "-v00")) {
			failures.add("command replay capture: " + capture.results());
		}

		return summary;
	}

	/** A template version this build lacks is refused before any operation starts. */
	private static String unavailable(ClientGameTestContext context, Path tampered, List<String> failures) {
		long started = context.computeOnClient(minecraft -> EnvironmentRuntime.get().status().operationsStarted());
		String result;
		try {
			await(context, () -> ReplayRuns.load(tampered, "s000000"));
			result = "replayed";
		} catch (ReplayException e) {
			result = e.toString();
		}

		long after = context.computeOnClient(minecraft -> EnvironmentRuntime.get().status().operationsStarted());
		if (!result.startsWith(ReplayException.Reason.UNAVAILABLE.name()) || after != started) {
			failures.add("unknown template version: " + result + ", " + (after - started) + " operations started");
		}

		return result;
	}

	private static String refusal(ClientGameTestContext context, Reference reference, String where, Enum<?> expected, List<String> failures) {
		String id = records(reference.directory()).getFirst().sceneId();
		String result;
		try {
			await(context, () -> ReplayRuns.load(reference.directory(), id));
			result = "replayed";
		} catch (ReplayException e) {
			result = e.toString();
		} catch (CompletionException e) {
			result = String.valueOf(Futures.cause(e));
		}

		if (!result.startsWith(expected.name())) {
			failures.add(reference.name() + " in " + where + ": expected " + expected + ", got " + result);
		}

		return result;
	}

	/** Runs {@code request} on the client and waits for it; a synchronous refusal is rethrown as it is. */
	private static <T> T await(ClientGameTestContext context, Supplier<CompletableFuture<T>> request) {
		CompletableFuture<T> future = context.computeOnClient(minecraft -> {
			try {
				return request.get();
			} catch (RuntimeException e) {
				return CompletableFuture.failedFuture(e);
			}
		});
		context.waitFor(minecraft -> future.isDone(), REPLAY_TICKS);
		try {
			return future.join();
		} catch (CompletionException e) {
			if (e.getCause() instanceof ReplayException replay) {
				throw replay;
			}

			throw e;
		}
	}

	private static void command(ClientGameTestContext context, String command) {
		context.runOnClient(minecraft -> minecraft.player.connection.sendCommand(command));
	}

	private static List<SceneRecord> records(Path directory) {
		try {
			return DatasetValidator.validate(directory).scenes();
		} catch (IOException e) {
			throw new UncheckedIOException(e);
		}
	}

	/** A copy of {@code dataset} whose first scene names a template version no build has. */
	private static Path tamperedCopy(Path dataset, Path copy) {
		try {
			Files.createDirectories(copy);
			for (String name : new String[] {"dataset.json", "samples.jsonl"}) {
				Files.copy(dataset.resolve(name), copy.resolve(name));
			}

			List<JsonObject> scenes = Jsonl.read(Files.readAllBytes(dataset.resolve("scenes.jsonl")), "scenes.jsonl");
			scenes.getFirst().getAsJsonObject("template").addProperty("version", 999);
			Files.write(copy.resolve("scenes.jsonl"), Jsonl.write(scenes));
			return copy;
		} catch (IOException e) {
			throw new UncheckedIOException(e);
		}
	}

	private static Map<String, String> hashes(Path directory) {
		Map<String, String> hashes = new TreeMap<>();
		try (Stream<Path> files = Files.walk(directory)) {
			for (Path file : files.filter(Files::isRegularFile).toList()) {
				hashes.put(directory.relativize(file).toString(), Sha256.hex(Files.readAllBytes(file)) + "@" + Files.getLastModifiedTime(file).toMillis());
			}
		} catch (IOException e) {
			throw new UncheckedIOException(e);
		}

		return hashes;
	}

	private static String config(String name, int level, int scenes, int viewpoints, String capture, String scene, Path root) {
		return """
			{
			  "dataset": {"name": "%s", "seed": %d, "difficulty": %d},
			  %s
			  "viewpoints": {"count": %d},
			  "capture": %s,
			  "quotas": {"accepted_scenes": %d},
			  "splits": {"train": 0.5, "validation": 0.25, "test": 0.25},
			  "target": {"present_fraction": 0.5},
			  "output": {"root": "%s", "free_space_reserve_bytes": 1073741824}
			}
			""".formatted(name, 8026 + level, level, scene, viewpoints, capture, scenes, root.toString().replace("\\", "\\\\"));
	}
}
