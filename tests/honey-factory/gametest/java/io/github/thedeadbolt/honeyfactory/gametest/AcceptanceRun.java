package io.github.thedeadbolt.honeyfactory.gametest;

import com.google.gson.GsonBuilder;
import com.google.gson.JsonArray;
import com.google.gson.JsonObject;
import io.github.thedeadbolt.honeyfactory.HoneyFactory;
import io.github.thedeadbolt.honeyfactory.client.generation.DatasetRuns;
import io.github.thedeadbolt.honeyfactory.contract.DatasetManifest;
import io.github.thedeadbolt.honeyfactory.generation.DatasetGenerator;
import io.github.thedeadbolt.honeyfactory.generation.GenerationTimings;
import java.io.IOException;
import java.io.UncheckedIOException;
import java.lang.management.ManagementFactory;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.Duration;
import java.time.LocalDateTime;
import java.time.format.DateTimeFormatter;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.stream.Stream;
import net.fabricmc.fabric.api.client.gametest.v1.context.ClientGameTestContext;
import net.fabricmc.fabric.api.client.gametest.v1.context.TestSingleplayerContext;

/**
 * Shared steps of the M9 acceptance runs. Datasets are generated by command, as an operator
 * would, into {@code <acceptance root>/<label>/<run>/} (the root defaults to
 * {@code /mnt/fastvault/minesophila/acceptance}, set {@code -Dhoneyfactory.acceptanceRoot}; the
 * label defaults to the start time, set {@code -Dhoneyfactory.acceptanceLabel}). Nothing is
 * deleted or overwritten. Each dataset's measurements go to {@code metrics/<dataset>.json}
 * beside it, and the dataset world is copied to {@code worlds/}, so level-5 scenes can be
 * replayed later.
 */
final class AcceptanceRun {
	private static final DateTimeFormatter LABEL = DateTimeFormatter.ofPattern("yyyy-MM-dd'T'HH-mm", Locale.ROOT);
	/** The first GPU that reports its VRAM use, or null. */
	private static final Path VRAM_USED = vramFile();
	private static String label;

	private AcceptanceRun() {
	}

	/** The directory of acceptance run {@code run}, created on first use. */
	static Path directory(String run) {
		if (label == null) {
			String given = System.getProperty("honeyfactory.acceptanceLabel", "");
			label = given.isBlank() ? LocalDateTime.now().format(LABEL) : given;
		}

		return directory(System.getProperty("honeyfactory.acceptanceRoot", ""), "/mnt/fastvault/minesophila/acceptance", label + "/" + run);
	}

	/** {@code <root or fallback>/<relative>}, created on first use with its {@code metrics} folder. */
	static Path directory(String root, String fallback, String relative) {
		Path directory = Path.of(root.isBlank() ? fallback : root).resolve(relative);
		try {
			Files.createDirectories(directory.resolve("metrics"));
		} catch (IOException e) {
			throw new UncheckedIOException(e);
		}

		return directory;
	}

	/** Creates and claims a dataset world, runs {@code body} in it, then copies the world to {@code worlds/}. */
	static void inWorld(ClientGameTestContext context, Path directory, String world, long seed, java.util.function.Consumer<TestSingleplayerContext> body) {
		try (TestSingleplayerContext singleplayer = GameTestSupport.datasetWorld(context, world, seed)) {
			GameTestSupport.claim(singleplayer, world);
			body.accept(singleplayer);
		}

		Path save = context.computeOnClient(minecraft -> minecraft.gameDirectory.toPath()).resolve("saves").resolve(world);
		copy(save, directory.resolve("worlds").resolve(world));
	}

	/**
	 * Generates {@code config} by command and writes its measurements to
	 * {@code metrics/<name>.json}; returns them.
	 */
	static JsonObject generate(ClientGameTestContext context, Path directory, String name, String config, int timeoutTicks) {
		resetPeakMemory();
		long[] peakVram = {vramUsed()};
		long[] peakHeap = {heapUsed()};
		long started = System.nanoTime();
		DatasetGenerator.Result result = GameTestSupport.generate(context, name, config, progress -> {
			peakVram[0] = Math.max(peakVram[0], vramUsed());
			peakHeap[0] = Math.max(peakHeap[0], heapUsed());
			return false;
		}, timeoutTicks);
		long wall = System.nanoTime() - started;
		peakVram[0] = Math.max(peakVram[0], vramUsed());
		peakHeap[0] = Math.max(peakHeap[0], heapUsed());

		DatasetManifest manifest = result.manifest();
		DatasetManifest.Counts counts = manifest.counts();
		JsonObject metrics = new JsonObject();
		metrics.addProperty("name", name);
		metrics.addProperty("dataset_id", manifest.datasetId());
		metrics.addProperty("directory", directory.relativize(result.directory()).toString());
		metrics.addProperty("lifecycle", manifest.lifecycle().jsonName());
		metrics.addProperty("failure", result.failure());
		metrics.add("validation_errors", new GsonBuilder().create().toJsonTree(result.validationErrors()));
		double seconds = manifest.completedAtUtc() == null ? wall / 1e9 : Duration.between(manifest.createdAtUtc(), manifest.completedAtUtc()).toMillis() / 1000.0;
		metrics.addProperty("seconds", seconds);
		metrics.addProperty("command_wall_seconds", wall / 1e9);
		metrics.addProperty("accepted_scenes", counts.acceptedScenes());
		metrics.addProperty("accepted_samples", counts.acceptedSamples());
		metrics.addProperty("attempted_scenes", counts.attemptedScenes());
		metrics.addProperty("rejected_scenes", counts.rejectedScenes());
		metrics.addProperty("failed_scenes", counts.failedScenes());
		metrics.add("rejection_reasons", new GsonBuilder().create().toJsonTree(counts.rejectionReasons()));
		metrics.addProperty("scenes_per_hour", counts.acceptedScenes() / seconds * 3600.0);
		metrics.addProperty("samples_per_hour", counts.acceptedSamples() / seconds * 3600.0);

		JsonObject phases = new JsonObject();
		for (Map.Entry<GenerationTimings.Phase, GenerationTimings.Total> entry : context.computeOnClient(minecraft -> DatasetRuns.lastTimings()).totals().entrySet()) {
			phases.add(entry.getKey().name().toLowerCase(Locale.ROOT), total(entry.getValue()));
		}

		metrics.add("phases", phases);
		List<long[]> captures = context.computeOnClient(minecraft -> DatasetRuns.lastCaptureSamples());
		JsonObject capture = new JsonObject();
		String[] parts = {"pose_wall", "render", "readback", "reproject"};
		for (int part = 0; part < parts.length; part++) {
			int index = part;
			capture.add(parts[part], total(GenerationTimings.Total.of(captures.stream().mapToLong(sample -> sample[index]).toArray())));
		}

		metrics.add("captures", capture);
		JsonObject memory = new JsonObject();
		memory.addProperty("peak_rss_bytes", peakRss());
		memory.addProperty("peak_heap_used_bytes", peakHeap[0]);
		memory.addProperty("max_heap_bytes", Runtime.getRuntime().maxMemory());
		memory.addProperty("peak_device_vram_used_bytes", peakVram[0]);
		memory.addProperty("sampling_note", "heap in use and amdgpu mem_info_vram_used (device-wide) sampled every " + GameTestSupport.PROGRESS_TICKS + " ticks; RSS is the kernel's peak");
		metrics.add("memory", memory);
		metrics.add("render_environment", manifest.renderEnvironment().toJson());
		try {
			Files.writeString(directory.resolve("metrics").resolve(name + ".json"), new GsonBuilder().setPrettyPrinting().create().toJson(metrics) + "\n", StandardCharsets.UTF_8);
		} catch (IOException e) {
			throw new UncheckedIOException(e);
		}

		HoneyFactory.LOGGER.info("Acceptance run {}: {} {} samples in {} s", name, manifest.lifecycle().jsonName(), counts.acceptedSamples(), seconds);
		return metrics;
	}

	private static JsonObject total(GenerationTimings.Total total) {
		JsonObject json = new JsonObject();
		json.addProperty("count", total.count());
		json.addProperty("seconds", total.seconds());
		json.addProperty("mean_seconds", total.meanSeconds());
		json.addProperty("p50_seconds", total.p50Seconds());
		json.addProperty("p95_seconds", total.p95Seconds());
		json.addProperty("max_seconds", total.maxSeconds());
		return json;
	}

	private static Path vramFile() {
		try (Stream<Path> cards = Files.list(Path.of("/sys/class/drm"))) {
			return cards.map(card -> card.resolve("device/mem_info_vram_used")).filter(Files::isReadable).sorted().findFirst().orElse(null);
		} catch (IOException e) {
			return null;
		}
	}

	/** Device-wide VRAM in use, or -1 where the driver does not report it. */
	private static long vramUsed() {
		if (VRAM_USED == null) {
			return -1;
		}

		try {
			return Long.parseLong(Files.readString(VRAM_USED).trim());
		} catch (IOException | NumberFormatException e) {
			return -1;
		}
	}

	/** Resets the kernel's peak-RSS counter, where possible. */
	private static void resetPeakMemory() {
		try {
			Files.writeString(Path.of("/proc/self/clear_refs"), "5");
		} catch (IOException ignored) {
			// Not Linux, or not permitted: the peak then covers the whole process.
		}
	}

	/** Java heap in use now. */
	private static long heapUsed() {
		return ManagementFactory.getMemoryMXBean().getHeapMemoryUsage().getUsed();
	}

	/** Peak resident set size since the last reset, from /proc, or -1. */
	private static long peakRss() {
		try (Stream<String> lines = Files.lines(Path.of("/proc/self/status"))) {
			return lines.filter(line -> line.startsWith("VmHWM:"))
				.map(line -> Long.parseLong(line.replaceAll("[^0-9]", "")) * 1024L)
				.findFirst()
				.orElse(-1L);
		} catch (IOException e) {
			return -1;
		}
	}

	private static void copy(Path from, Path to) {
		try (Stream<Path> files = Files.walk(from)) {
			for (Path file : files.toList()) {
				Path target = to.resolve(from.relativize(file).toString());
				if (Files.isDirectory(file)) {
					Files.createDirectories(target);
				} else if (!file.getFileName().toString().equals("session.lock")) {
					Files.copy(file, target);
				}
			}
		} catch (IOException e) {
			throw new UncheckedIOException(e);
		}
	}

	/** {@code {"runs": [...]}} for a run's datasets, written as {@code metrics/summary.json}. */
	static void summary(Path directory, List<JsonObject> runs) {
		JsonObject summary = new JsonObject();
		JsonArray list = new JsonArray();
		runs.forEach(list::add);
		summary.add("runs", list);
		try {
			Files.writeString(directory.resolve("metrics").resolve("summary.json"), new GsonBuilder().setPrettyPrinting().create().toJson(summary) + "\n", StandardCharsets.UTF_8);
		} catch (IOException e) {
			throw new UncheckedIOException(e);
		}
	}
}
